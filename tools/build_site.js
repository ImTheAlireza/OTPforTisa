/* ------------------------------------------------------------ comments out */

let acorn = null;

function jsComments(text) {
	if (!acorn) {
		try {
			acorn = require('acorn');
		} catch (error) {
			fail('acorn is needed to build the site: npm install --no-save acorn');
		}
	}

	const ranges = [];
	acorn.parse(text, { ecmaVersion: 'latest', sourceType: 'script', onComment: (block, body, start, end) => ranges.push([start, end]) });
	return ranges;
}

function cssComments(text) {
	const ranges = [];
	let quote = null;

	for (let i = 0; i < text.length; i++) {
		const c = text[i];
		if (quote) {
			if (c === '\\') {
				i++;
			} else if (c === quote) {
				quote = null;
			}
		} else if (c === '"' || c === "'") {
			quote = c;
		} else if (c === '/' && text[i + 1] === '*') {
			const end = text.indexOf('*/', i + 2);
			ranges.push([i, end + 2]);
			i = end + 1;
		}
	}

	return ranges;
}

function cut(text, ranges) {
	if (!ranges.length) {
		return text;
	}

	let out = '';
	let at = 0;
	for (const [a, b] of ranges) {
		out += text.slice(at, a) + '\u0000';
		at = b;
	}
	out += text.slice(at);

	return out
		.split('\n')
		.filter((line) => !(line.includes('\u0000') && line.replace(/\u0000/g, '').trim() === ''))
		.map((line) => (line.includes('\u0000') ? line.replace(/\u0000/g, '').replace(/[ \t]+$/, '') : line))
		.join('\n')
		.replace(/\n{3,}/g, '\n\n');
}

function htmlComments(text) {
	const parts = text.split(/(<script\b[^>]*>[\s\S]*?<\/script>|<style\b[^>]*>[\s\S]*?<\/style>)/);

	return parts
		.map((part, i) => {
			if (i % 2 === 0) {
				const ranges = [];
				part.replace(/<!--[\s\S]*?-->/g, (m, at) => ranges.push([at, at + m.length]));
				return cut(part, ranges);
			}
			const m = /^(<(script|style)\b[^>]*>)([\s\S]*?)(<\/\2>)$/.exec(part);
			if (m[2] === 'style') {
				return m[1] + cut(m[3], cssComments(m[3])) + m[4];
			}
			if (/\bsrc=|type="application\/(ld\+)?json"/.test(m[1]) || !m[3].trim()) {
				return part;
			}
			return m[1] + cut(m[3], jsComments(m[3])) + m[4];
		})
		.join('');
}

function withoutComments(name, data) {
	if (/\.js$/.test(name)) {
		return cut(data, jsComments(data));
	}
	if (/\.css$/.test(name)) {
		return cut(data, cssComments(data));
	}
	if (/\.html$/.test(name)) {
		return htmlComments(data);
	}
	if (/\.htaccess$/.test(name)) {
		return data.replace(/^#.*\n/gm, '');
	}
	return data;
}

/* ------------------------------------------------------------------ output */

function files() {
	const out = new Map();
	const put = (name, data) => {
		const text = /\.(html|js|css|htaccess)$/.test(name) ? withoutComments(name, data.toString('utf8')) : data;
		out.set(name, Buffer.isBuffer(text) ? text : Buffer.from(text, 'utf8'));
	};
	const copy = (name, ...src) => put(name, fs.readFileSync(path.join(...src)));

	const mock = mockScript();
	const shared = (root, admin) => {
		copy(root + '/assets/css/front.css', ASSETS, 'css', 'front.css');
		copy(root + '/assets/js/front.js', ASSETS, 'js', 'front.js');
		for (const font of fs.readdirSync(path.join(ASSETS, 'fonts')).sort()) {
			if (/\.(woff2|txt)$/.test(font)) {
				copy(root + '/assets/fonts/' + font, ASSETS, 'fonts', font);
			}
		}
		if (admin) {
			copy(root + '/assets/css/admin.css', ASSETS, 'css', 'admin.css');
			copy(root + '/assets/js/admin.js', ASSETS, 'js', 'admin.js');
		}
		put(root + '/assets/js/demo-mock.js', mock);
		copy(root + '/assets/js/demo-shim.js', SITE, 'shared', 'demo-shim.js');
		copy(root + '/assets/js/demo-phone.js', SITE, 'shared', 'demo-phone.js');
		copy(root + '/assets/demo-phone.css', SITE, 'shared', 'demo-phone.css');
		copy(root + '/assets/js/demo-studio.js', SITE, 'shared', 'demo-studio.js');
		copy(root + '/assets/js/site.js', SITE, 'shared', 'site.js');
		copy(root + '/assets/landing.css', SITE, 'landing', 'landing.css');
		put(root + '/.htaccess', HTACCESS);
	};

	shared('signa', false);
	put('signa/index.html', landing());

	shared('signa/demo', true);
	copy('signa/demo/assets/demo.css', SITE, 'shared', 'demo.css');
	put('signa/demo/index.html', demoIndex());
	put('signa/demo/account.html', demoAccount());
	put('signa/demo/woodmart.html', demoWoodmart());

	for (const file of fs.readdirSync(PREVIEW).sort()) {
		if (/^admin(-[a-z]+)?\.html$/.test(file) && !/^admin-preview-/.test(file)) {
			put('signa/demo/' + file, demoAdmin(file));
		} else if (/^admin-preview-[a-z]+\.html$/.test(file)) {
			put('signa/demo/' + file, rewrite(read(PREVIEW, file)));
		}
	}

	return out;
}

/* What must never reach a public page. */
function audit(out) {
	const problems = [];

	for (const [name, data] of out) {
		if (!/\.(html|js|css)$/.test(name)) {
			continue;
		}

		const text = data.toString('utf8');

		if (/\.html$/.test(name)) {
			const rooted = text.match(/(?:href|src|action|data-url)="\/(?!\/)[^"]*"/g);
			if (rooted) {
				problems.push(name + ': root-relative address ' + rooted[0] + ' (breaks under a sub-folder)');
			}
			if (/download\/signa\.zip|signa\.zip"/.test(text)) {
				problems.push(name + ': links to the plugin package');
			}
			if (/\/mock\//.test(text)) {
				problems.push(name + ': still points at the preview server mock');
			}
		}

		if (/\/mock\/signa\//.test(text)) {
			problems.push(name + ': still points at the preview server mock');
		}

		if (/t\.me\/|instagram\.com|wa\.me\/|mailto:|@gmail\.|github\.com\/(?!rastikerdar)/i.test(text)) {
			problems.push(name + ': personal link or contact');
		}

		// Written as a character class so the brand check does not match this file.
		if (/t[i]sa|ت[ی]سا/i.test(text)) {
			problems.push(name + ': old client name');
		}
	}

	if (problems.length) {
		fail('refusing to write the site:\n  ' + problems.join('\n  '));
	}
}

function walk(dir, base = dir, list = []) {
	if (!fs.existsSync(dir)) {
		return list;
	}

	for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
		const full = path.join(dir, entry.name);
		if (entry.isDirectory()) {
			walk(full, base, list);
		} else {
			list.push(path.relative(base, full).split(path.sep).join('/'));
		}
	}

	return list;
}

function main() {
	const out = files();
	audit(out);

	if (process.argv.includes('--check')) {
		const onDisk = new Set(walk(OUT));
		const drift = [];

		for (const [name, data] of out) {
			const target = path.join(OUT, name);
			if (!fs.existsSync(target) || !fs.readFileSync(target).equals(data)) {
				drift.push(name);
			}
			onDisk.delete(name);
		}

		drift.push(...[...onDisk].map((name) => name + ' (stale)'));

		if (drift.length) {
			fail('web/ is out of date; run node tools/build_site.js\n  ' + drift.slice(0, 20).join('\n  '));
		}

		console.log('site check ok: ' + out.size + ' files');
		return;
	}

	fs.rmSync(OUT, { recursive: true, force: true });

	let bytes = { signa: 0, demo: 0 };
	for (const [name, data] of out) {
		const target = path.join(OUT, name);
		fs.mkdirSync(path.dirname(target), { recursive: true });
		fs.writeFileSync(target, data);
		bytes[name.startsWith('signa/demo/') ? 'demo' : 'signa'] += data.length;
	}

	const kb = (n) => Math.round(n / 1024) + ' KB';
	console.log('wrote web/signa (' + kb(bytes.signa) + ') with the demo in web/signa/demo (' + kb(bytes.demo) + '), ' + out.size + ' files, version ' + version);
}

main();
