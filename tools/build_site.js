#!/usr/bin/env node
/**
 * Build the two public sites from the plugin itself:
 *
 *   web/signa/        the landing page   → parsena.ir/signa/
 *   web/signa/demo/   the live demo      → parsena.ir/signa/demo/
 *
 * One folder to upload: web/signa goes to public_html/signa. The two pages
 * link to each other with relative addresses, so they work on any domain.
 *
 * Both are plain static files (no PHP, no database), sized for a small host.
 * Nothing is drawn by hand twice:
 *
 * - the form, its stylesheet, its script and the fonts are the plugin's own
 *   files from signa/assets;
 * - the admin screens are the pages tools/admin-demo.js generates from the
 *   plugin's real PHP output (preview/public/admin*.html);
 * - the REST answers are the mock backend of preview/server.js, lifted out at
 *   build time and run inside the browser by site/shared/demo-shim.js.
 *
 * Usage:
 *   node tools/build_site.js           write web/
 *   node tools/build_site.js --check   exit 1 when web/ is not what this builds
 */
'use strict';

const fs = require('fs');
const path = require('path');

const REPO = path.join(__dirname, '..');
const SITE = path.join(REPO, 'site');
const PREVIEW = path.join(REPO, 'preview', 'public');
const ASSETS = path.join(REPO, 'signa', 'assets');
const OUT = path.join(REPO, 'web');

const read = (...parts) => fs.readFileSync(path.join(...parts), 'utf8');

/* ------------------------------------------------------------------ inputs */

const config = JSON.parse(read(SITE, 'site.json'));
const version = /Version:\s*([0-9.]+)/.exec(read(REPO, 'signa', 'signa.php'))[1];
const faDigits = (text) => String(text).replace(/[0-9]/g, (d) => '۰۱۲۳۴۵۶۷۸۹'[d]);
const versionFa = faDigits(version);

function fail(message) {
	console.error('build_site: ' + message);
	process.exit(1);
}

function between(text, start, end, label) {
	const a = text.indexOf(start);
	const b = text.indexOf(end, a + start.length);

	if (a < 0 || b < 0) {
		fail('marker not found for ' + label + ': ' + (a < 0 ? start : end));
	}

	return { before: text.slice(0, a), inner: text.slice(a + start.length, b), after: text.slice(b + end.length), start: a, end: b };
}

function replaceOnce(text, find, replacement, label) {
	const at = typeof find === 'string' ? text.indexOf(find) : text.search(find);

	if (at < 0) {
		fail('pattern not found (' + label + '): ' + find);
	}

	return text.replace(find, replacement);
}

/* The mock backend, as written in preview/server.js, wrapped for a browser. */
function mockScript() {
	const server = read(REPO, 'preview', 'server.js');
	const part = between(
		server,
		'/* ------------------------------------------------------------- mock backend */',
		'/* -------------------------------------------------------------- http server */',
		'mock backend'
	).inner;

	if (/require\(|process\.|fs\.|__dirname/.test(part)) {
		fail('the mock section of preview/server.js now uses Node APIs; it must stay browser-safe');
	}

	return [
		'/* Generated by tools/build_site.js from preview/server.js (mock backend). Do not edit. */',
		'(function () {',
		"\t'use strict';",
		// /form-config hands out the REST address and the form adopts it.
		part.trim().replace(/\/mock\/signa\/v1\//g, 'demo-api/signa/v1/'),
		'',
		'\twindow.SignaDemoMock = { handleRest: handleRest };',
		'})();',
		'',
	].join('\n');
}

/* -------------------------------------------------------------- rewriting */

function rewrite(html) {
	return html
		.replace(/\/plugin-assets\//g, 'assets/')
		.replace(/\/mock\/signa\/v1\//g, 'demo-api/signa/v1/')
		.replace(/(src|data-url)="\/admin\/form-preview"/g, (m, attr) => (attr === 'src' ? 'src="admin-preview-phone.html"' : 'data-url="form-preview"'))
		// Screen links keep their query and fragment. The generator prints the
		// reports range as `/admin/reports&amp;range=7`; the first & is a ?.
		.replace(/href="\/admin\/(settings|reports|logs|tools|access)([?&#][^"]*)?"/g, (m, screen, rest) => {
			const tail = (rest || '').replace(/^&(amp;)?/, '?');
			return 'href="admin-' + screen + '.html' + tail + '"';
		})
		.replace(/href="\/admin"/g, 'href="admin.html"')
		.replace(/href="\/account"/g, 'href="account.html"')
		.replace(/href="\/woodmart"/g, 'href="woodmart.html"')
		.replace(/href="\/"/g, 'href="index.html"');
}

